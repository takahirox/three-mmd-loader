"""Run inside the pinned Emscripten container; all inputs live under /work."""
import hashlib
import json
import os
import re
from pathlib import Path
import subprocess

os.chdir('/work')
root = Path('experiments/bullet')
lock = json.loads((root / 'source.json').read_text())
source = Path('.cache/bullet-experiment/source')
build = Path('.cache/bullet-experiment/build')
output = Path('examples/vendor/bullet')
build.mkdir(parents=True, exist_ok=True)
output.mkdir(parents=True, exist_ok=True)

def run(*args):
    subprocess.run(args, check=True)

version = subprocess.check_output(['emcc', '--version'], text=True).splitlines()[0]
if '4.0.10' not in version:
    raise RuntimeError('Expected Emscripten 4.0.10, got ' + version)
git = ['git', '-c', 'safe.directory=/work/' + str(source), '-C', str(source)]
if subprocess.check_output([*git, 'rev-parse', 'HEAD'], text=True).strip() != lock['bulletCommit']:
    raise RuntimeError('Bullet checkout does not match source.json')
if subprocess.check_output([*git, 'status', '--porcelain'], text=True).strip():
    raise RuntimeError('Bullet source must be unmodified')
run('python3', '/emsdk/upstream/emscripten/tools/webidl_binder.py', str(root / 'bindings.idl'), str(build / 'bindings'))
with (build / 'bindings.js').open('a') as glue:
    glue.write('\nModule["getWasmExports"] = () => wasmExports;\n')
    glue.write('Module["bulletCommit"] = ' + json.dumps(lock['bulletCommit']) + ';\n')
(build / 'bindings.cpp.generated').write_bytes((build / 'bindings.cpp').read_bytes())
(build / 'CMakeLists.txt').write_text('''cmake_minimum_required(VERSION 3.16)
project(MMDExperimentalBullet)
set(CMAKE_CXX_FLAGS "-O3 -DNDEBUG -fno-exceptions -fno-rtti")
file(GLOB_RECURSE SOURCES /work/.cache/bullet-experiment/source/src/BulletCollision/*.cpp /work/.cache/bullet-experiment/source/src/BulletDynamics/*.cpp /work/.cache/bullet-experiment/source/src/LinearMath/*.cpp)
add_library(bullet STATIC ${SOURCES})
target_include_directories(bullet PUBLIC /work/.cache/bullet-experiment/source/src)
''')
run('emcmake', 'cmake', '-S', str(build), '-B', str(build / 'cmake'), '-DCMAKE_BUILD_TYPE=Release')
run('cmake', '--build', str(build / 'cmake'), '-j4')
flags = ['-O3', '-DNDEBUG', '-fno-exceptions', '-fno-rtti', '-sMODULARIZE=1', '-sEXPORT_NAME=Ammo',
         '-sENVIRONMENT=web,worker,node', '-sALLOW_MEMORY_GROWTH=1', '-sINITIAL_MEMORY=33554432',
         '-sFILESYSTEM=0', '-sASSERTIONS=1', '-sEXPORTED_FUNCTIONS=["_malloc","_free"]',
         '-sEXPORTED_RUNTIME_METHODS=["HEAP8","HEAPU8"]', '-sWASM_ASYNC_COMPILATION=1', '-sSINGLE_FILE=0']
run('em++', str(root / 'bindings.cpp'), str(build / 'cmake/libbullet.a'), '-I' + str(source / 'src'),
    '-I' + str(build), '--post-js', str(build / 'bindings.js'), *flags, '-o', str(output / 'ammo.js'))
glue_path = output / 'ammo.js'
glue_path.write_text('/* Generated by experiments/bullet/build.py from official Bullet ' + lock['bulletCommit'] +
                     '. Bullet: zlib; Emscripten: MIT/NCSA. See adjacent LICENSE.*.txt and manifest.json. */\n' + glue_path.read_text())
(output / 'ammo.wasm').chmod(0o644)
(output / 'LICENSE.Bullet.txt').write_bytes((source / 'LICENSE.txt').read_bytes())
# Retain the individual authors' notices too (GIMPACT, Melax, etc.). Deduplicate
# identical opening comments, without editing their original attribution text.
notices = {}
for component in ['BulletCollision', 'BulletDynamics', 'LinearMath']:
    for path in sorted((source / 'src' / component).rglob('*')):
        if path.suffix not in ['.h', '.cpp']:
            continue
        text = path.read_text(errors='replace').lstrip()
        while True:
            match = re.match(r'/\*.*?\*/|(?://[^\n]*(?:\n|$))+', text, re.S)
            if not match:
                break
            notice = match.group(0)
            if re.search(r'copyright|license|permission|public domain', notice, re.I):
                notices.setdefault(notice, []).append(str(path.relative_to(source)))
            text = text[match.end():].lstrip()
(output / 'LICENSE.Bullet-source-notices.txt').write_text('\n\n'.join('\n'.join(paths) + '\n\n' + notice for notice, paths in notices.items()) + '\n')
(output / 'LICENSE.Emscripten.txt').write_bytes(Path('/emsdk/upstream/emscripten/LICENSE').read_bytes())
system_lib = Path('/emsdk/upstream/emscripten/system/lib')
for name, relative in {'musl': 'libc/musl/COPYRIGHT', 'libcxx': 'libcxx/LICENSE.TXT',
                       'libcxxabi': 'libcxxabi/LICENSE.TXT', 'compiler-rt': 'compiler-rt/LICENSE.TXT'}.items():
    (output / ('LICENSE.' + name + '.txt')).write_bytes((system_lib / relative).read_bytes())
# dlmalloc's embedded public-domain dedication is retained with its source header.
(output / 'LICENSE.dlmalloc.txt').write_text((system_lib / 'dlmalloc.c').read_text().split('#ifndef DLMALLOC_VERSION')[0])
manifest = {**lock, 'compiler': version, 'flags': flags, 'patches': [],
            'recipeSha256': {path.name: hashlib.sha256(path.read_bytes()).hexdigest()
                             for path in [root / 'build.py', root / 'bindings.idl', root / 'bindings.cpp']},
            'sha256': {}}
for path in sorted(output.iterdir()):
    if path.name != 'manifest.json':
        manifest['sha256'][path.name] = hashlib.sha256(path.read_bytes()).hexdigest()
(output / 'manifest.json').write_text(json.dumps(manifest, indent=2) + '\n')
